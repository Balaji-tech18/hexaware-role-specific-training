list = [1,2,3,4,5,6,7,8]

print("Printing the entire list!")
print(list)

print("Accessing using Index")
print(list[0])
print(list[1])

print("Updating")
list[2] = 0

print(list)

print("Appending")
list.append(9)
print(list)

print("Inserting")
list.insert(4,10)
print(list)

print("Removing")
list.remove(4)
print(list)

print("Poping")
list.pop()
print(list)